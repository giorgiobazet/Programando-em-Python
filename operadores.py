#Aritméticos

x = 10
y = 5

print(x + y)  # Adição
print(x - y)  # Subtração
print(x * y)  # Multiplicação
print(x / y)  # Divisão
print(x // y)  # Divisão inteira
print(x % y)  # Resto da divisão
print(x ** y)  # Exponenciação
print("")

#Comparação

x = 10
y = 5

print(x > y)  # Maior que
print(x < y)  # Menor que
print(x == y)  # Igual a
print(x != y)  # Diferente de
print(x >= y)  # Maior ou igual a
print(x <= y)  # Menor ou igual a
print("")

#Lógicos

x = 10
y = 5

print(x > 5 and y < 10)  # E
print(x > 5 or y < 10)   # Ou
print(not(x > 5))        # Não
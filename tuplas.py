#métodos de tuplas

minha_tupla = (1, 2, 3, 2, 4, 2)

#count (Contando elementos na tupla)
print(minha_tupla.count(2))  # Contando quantas vezes o número 2 aparece na tupla

#index (Encontrando o índice de um elemento na tupla)
print(minha_tupla.index(3))  # Encontrando o índice do número 3 na tupla

#len (Obtendo o tamanho da tupla)

print(len(minha_tupla))  # Obtendo o tamanho da tupla